import type { HTMLAttributes } from 'react';

/**
 * Атрибуты СВЁРНУТОЙ области.
 *
 * Раскрывашки системы прячут содержимое высотой: `grid-template-rows: 0fr` плюс
 * `overflow: hidden`. Пиксели исчезают — УЗЛЫ остаются. А значит остаются и в порядке
 * таба, и в дереве доступности: человек жмёт Tab и получает десяток нажатий в никуда, а
 * скринридер читает закрытую подсказку как обычный текст.
 *
 * Ровно так витрина ловила фокус: под каждым компонентом лежит блок «Примеры», в нём —
 * живые поля и слайдеры, и после панели острова таб уходил в них, до следующей кнопки не
 * доходя. Со стороны это выглядит как «таб пропускает кнопку».
 *
 * Лечится атрибутом `inert`: он убирает поддерево и из таба, и из дерева доступности, и
 * из попадания указателя, НЕ трогая отрисовку — поэтому анимация закрытия остаётся живой.
 * Ни `display:none`, ни `visibility:hidden` так не умеют: они гасят содержимое мгновенно,
 * и выход схлопывается рывком по пустой коробке.
 *
 * Держит гейт tests/showcase/focus.spec.js.
 */
export function collapsedProps(collapsed: boolean): HTMLAttributes<HTMLElement> {
  // `inert` описан в типах React только с 19-й версии, а пакет собирается на 18-й.
  // Значение — пустая строка, а не true: неизвестный булев проп React 18 не рендерит
  // вовсе, тогда как `inert=""` браузер читает как «включено».
  return collapsed ? ({ inert: '' } as HTMLAttributes<HTMLElement>) : {};
}
