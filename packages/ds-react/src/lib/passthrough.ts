/**
 * Каналы наружу: то, что потребитель обязан уметь навесить на любой компонент.
 *
 * До этого щель была одна — `style`. Следствия были не косметические: `react-hook-form`
 * не подключить (нужен `ref`), `data-testid` не поставить (весь тест-сьют потребителя
 * обязан искать по роли и тексту), `aria-describedby` к внешнему сообщению не привязать,
 * класс для лейаута не навесить. Хуже того, `aria-label` и `data-testid` ПРОХОДИЛИ
 * проверку типов и молча терялись: TypeScript не ловит лишние свойства с дефисом.
 *
 * Что сюда НЕ входит и почему: `title` — браузерная подсказка, у системы своя (`tooltip`,
 * см. CLAUDE.md); `onClick` и прочие обработчики объявлены у компонентов явно, потому что
 * у ряда и у контрола внутри него это разные события.
 */
export interface PassThrough {
  /** Класс на корень — для лейаута снаружи. Внутренние стили инлайновые и не конфликтуют. */
  className?: string;
  /** Идентификатор корня — чтобы к нему можно было сослаться из aria-* снаружи. */
  id?: string;
  /** data-* уезжают на корень как есть: тестовые хуки и разметка аналитики. */
  [dataAttr: `data-${string}`]: unknown;
  /** aria-* уезжают на корень как есть: описание, связи, живые области. */
  [ariaAttr: `aria-${string}`]: unknown;
}

/**
 * Отобрать из пропсов только то, что уезжает на корень.
 *
 * Берём не «всё лишнее», а именно эти каналы: случайная опечатка в имени пропа не должна
 * превращаться в атрибут разметки — иначе `<Button lable="Ок">` тихо отрендерит `lable`.
 */
export function passThrough(props: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(props)) {
    if (v === undefined) continue;
    if (k === 'className' || k === 'id' || k.startsWith('data-') || k.startsWith('aria-')) out[k] = v;
  }
  return out;
}
