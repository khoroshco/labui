import { useEffect, useState, type ReactNode } from 'react';
import { createPortal } from 'react-dom';

/**
 * Слой над содержимым: попап селекта, модалка.
 *
 * Зачем портал, а не «просто absolute рядом». Всплывающее, оставшееся в потоке, режется
 * первым же предком с `overflow: hidden` — а у нас такой предок есть по построению:
 * геометрией углов владеет остров и режет им же (docs/design-system.md), и ровно поэтому
 * тултипы внутри острова не живут. Тот же `overflow` есть у карточки, у канваса нарезки и
 * у любой прокручиваемой панели потребителя. Второе — `z-index`: соседний блок с бóльшим
 * значением накрывает выпадашку, и это не чинится изнутри компонента.
 *
 * `position: fixed` внутри портала мимо всего этого проходит. Но fixed ломается о предка
 * с `transform`/`filter`/`perspective` (он становится содержащим блоком), а такой предок
 * у потребителя вероятен — карточка с ховер-анимацией. Портал в `document.body` убирает
 * и это: у body предков нет.
 *
 * ЧЕГО ЭТО СТОИТ И ЧТО НАДО ЗНАТЬ. Тема живёт на `html[data-theme]`, поэтому в портале
 * она работает. Но если потребитель повесил тему НА СВОЙ УЗЕЛ (тёмная панель внутри
 * светлой страницы), содержимое портала останется в теме документа: оно физически лежит
 * не внутри его узла. Обхода без пропа-контейнера нет, и проп мы не заводим, пока такой
 * случай не появится — предполагаемая гибкость дороже отсутствующей.
 *
 * SSR: `document` на сервере нет, поэтому до монтирования слой не рисуется вовсе. Это
 * правильно и по существу — попап и модалка не имеют смысла в разметке, отданной без JS.
 */
export function Layer({ children }: { children: ReactNode }) {
  const [host, setHost] = useState<HTMLElement | null>(null);
  useEffect(() => {
    setHost(document.body);
  }, []);
  return host ? createPortal(children, host) : null;
}
