/* ЧТО ЛЕЖИТ В ДЕРЕВЕ: не «стиль», а работоспособность чужого чекаута.
 *
 * Дыра, ради которой заведено. В main приехал ОТСЛЕЖИВАЕМЫЙ СИМЛИНК `node_modules`,
 * указывающий на абсолютный путь ноутбука автора. Появился он не из злого умысла:
 * параллельные ветки жили в git-worktree, зависимости в них подкладывались ссылкой на
 * общий каталог, а `.gitignore` говорил `node_modules/` — со слэшем, то есть про
 * КАТАЛОГИ. Симлинк каталогом не является, под шаблон не попал, и `git add -A` внёс его
 * в индекс как обычный файл.
 *
 * Дальше цепочка, в которой ни один гейт не покраснел:
 *   — CI жив: `npm ci` сносит «не-каталог» (`npm warn reify Removing non-directory ...`)
 *     и раскладывает зависимости по-настоящему. Все сюиты зелёные;
 *   — релиз мёртв: `changesets/action` делает `npm ci`, а ПОТОМ `git reset --hard`, и
 *     reset возвращает симлинк на место установленных пакетов. Следующая же команда —
 *     `npx changeset version` — отвечает «could not determine executable to run».
 *     Релиз 0.4.0 не вышел, а сообщение об ошибке не содержит слова `node_modules`.
 *
 * Мера здесь — СЛЕДСТВИЕ, а не признак: не «в .gitignore правильный шаблон», а «в индексе
 * лежит запись, которой в чужом чекауте взяться неоткуда». Проверок две, и вторая не
 * дублирует первую: симлинк ломает чекаут даже когда он не игнорируется, а
 * закоммиченный `dist/` игнорируется, но симлинком не является.
 */
import { execFileSync } from 'node:child_process';
import { report, ROOT } from './lib/dc.mjs';

const git = (...args) =>
  execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })
    .split('\n')
    .filter(Boolean);

const problems = [];

// 1. Симлинки. Режим 120000 — это и есть «в индексе не файл, а ссылка».
//
// Список исключений здесь НЕ предусмотрен намеренно: у дизайн-системы нет причины возить
// ссылку в пакете, а «одно исключение» — обычный способ вернуть ровно эту поломку.
for (const line of git('ls-files', '-s')) {
  const [mode, , , ...rest] = line.split(/\s+/);
  if (mode === '120000') {
    const file = rest.join(' ');
    const target = git('show', `:${file}`)[0] ?? '';
    problems.push(
      `${file} — отслеживаемый симлинк на «${target}». В чужом чекауте это битая ссылка; ` +
        'если она называется node_modules, релиз падает на «could not determine executable to run».'
    );
  }
}

// 2. Отслеживается то, что сами же объявили игнорируемым.
//
// Список выводится из `.gitignore`, а не пишется руками: гейт не может разойтись с
// правилом, которое сторожит. Ловит закоммиченный `dist/`, отчёты прогонов и снятые
// вслепую артефакты — всё, что раздувает клон и уезжает к потребителю в пакете.
for (const file of git('ls-files', '-i', '-c', '--exclude-standard')) {
  problems.push(`${file} — отслеживается, хотя .gitignore объявляет этот путь игнорируемым`);
}

process.exit(report('Дерево: ни симлинков, ни закоммиченного мусора', problems));
