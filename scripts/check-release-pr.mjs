/* ГЕЙТ СОСТАВА РЕЛИЗНОГО PR.
 *
 * Браузерные сюиты на релизной ветке не запускаются: там лежат ровно две вещи — версии в
 * package.json и CHANGELOG, — и проверять в них вёрстку нечего. За всё время они
 * прогнались там 36 раз и стоили 249 биллинг-минут.
 *
 * Но «нечего проверять» — это утверждение о СОСТАВЕ, а не о ветке. Стоит однажды попасть
 * туда правке исходников — своей, чужой или сгенерированной, — и пропуск сюит из экономии
 * превращается в дыру: код уедет к потребителю, не увидев ни одного браузерного гейта.
 *
 * Поэтому исключение и его страховка живут вместе: сюиты пропускаются, а состав
 * доказывается здесь. Тронул что-то кроме версий — прогон красный, и сюиты ни при чём.
 */
import { execSync } from 'node:child_process';

const base = process.env.GITHUB_BASE_REF ? `origin/${process.env.GITHUB_BASE_REF}` : 'origin/main';

/** Что релизному PR трогать МОЖНО. Список закрытый: его пишет changesets, и больше никто. */
const ALLOWED = [
  /^\.changeset\//, // записи, которые релиз ТРАТИТ
  /^packages\/[^/]+\/package\.json$/, // версия пакета
  /^packages\/[^/]+\/CHANGELOG\.md$/, // история версий
];

const changed = execSync(`git diff --name-only ${base}...HEAD`, { encoding: 'utf8' })
  .split('\n')
  .map((s) => s.trim())
  .filter(Boolean);

// Страховка от тихой пустоты: релизный PR без единой правки — это не «чисто», это
// «сравнили не с тем», и зелёный результат тут означал бы ровно ничего.
if (changed.length === 0) {
  console.error('✗ релизный PR не изменил ни одного файла — диапазон сравнения собран не из того места');
  process.exit(1);
}

const bad = changed.filter((f) => !ALLOWED.some((re) => re.test(f)));
if (bad.length) {
  console.error(
    '✗ релизный PR тронул не только версии, а браузерные сюиты на нём ПРОПУСКАЮТСЯ.\n\n' +
      '  Лишнее:\n' +
      bad.map((f) => `    ${f}`).join('\n') +
      '\n\n  Либо эта правка едет обычным PR, либо исключение из сюит перестаёт быть правдой.\n'
  );
  process.exit(1);
}

console.log(`✓ состав релизного PR — только версии и CHANGELOG (${changed.length} файлов)`);
